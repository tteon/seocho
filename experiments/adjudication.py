#!/usr/bin/env python3
"""Build a packet a person can actually label, and read it back when they have.

The oracle-ceiling artifact ends with a requirement rather than a result:
"Repeat this ceiling on independently human-labeled mixed questions before
optimizing the router." Two hundred and forty candidate cross-category questions
exist and every one carries `human_validation_status: pending`. The generator
was built; the form was not.

What the labeller is actually deciding, and it is not a formality: FinDER has no
natively multi-source question. Every reference in a multi-reference case is a
different section of one issuer's filing. So these candidates are **synthesized**
— two single-reference questions from different categories, paired because a
regex found the same ticker in both. Three things can be wrong with that, and
the packet surfaces the evidence for each:

    wrong issuer      the ticker was pulled from the question text by
                      "last uppercase 2-5 letter token", so a competitor
                      mentioned in passing becomes the subject
    not composite     the pair reads as two questions stapled together rather
                      than one question needing both
    no joint answer   the two gold answers do not combine into anything a
                      person would call an answer

A candidate failing any of these is not usable, and marking it so is the point.
An unlabelled packet is worth nothing; a packet labelled to keep everything is
worth less than nothing, because it launders synthesis into ground truth.

    python3 experiments/adjudication.py --build --sample 40
    # fill adjudication/packet.csv, then
    python3 experiments/adjudication.py --read
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CANDIDATES = (ROOT / "outputs/evaluation/mdm_fedcat/log2026-full-finder-cross-view-v1"
              / "candidates.json")
PACKET_DIR = ROOT / "adjudication"
PACKET = PACKET_DIR / "packet.csv"
OUT_ROOT = ROOT / "outputs/minimal"

COLUMNS = [
    "candidate_id", "split", "issuer", "categories",
    "question_1", "question_2",
    # Filled by the labeller. Everything above is evidence, everything below is
    # judgement, and the two are kept apart so a half-finished packet is
    # obviously half-finished.
    "issuer_correct", "is_composite", "joint_answer_exists",
    "composite_question", "composite_answer", "notes",
]

GUIDE = """# Cross-category question adjudication

240 candidates were generated by pairing two single-reference FinDER questions
from different categories that a regex judged to be about the same issuer. This
packet asks whether that pairing produced a real question.

Fill the last six columns of `packet.csv`. Leave a row blank to skip it; a
blank row is treated as unlabelled, never as approved.

| Column | Answer with | Means |
|---|---|---|
| `issuer_correct` | yes / no | Are both questions about the company named in `issuer`? The ticker was extracted as the last uppercase 2-5 letter token in the question, so a competitor or a regulator mentioned in passing can end up here. |
| `is_composite` | yes / no | Does answering need **both** questions, or are they two separate questions side by side? If either could be answered alone and the pair adds nothing, answer no. |
| `joint_answer_exists` | yes / no | Do the two gold answers combine into something a person would call one answer? |
| `composite_question` | free text | If composite, the single question a user would actually ask. Leave blank otherwise. |
| `composite_answer` | free text | The answer to that question, drawn from the two golds. This becomes the gold for the routing measurement. |
| `notes` | free text | Anything that made the call hard. Read later; genuinely used. |

Answer `no` freely. The measurement this feeds needs candidates that are real,
not candidates that are numerous, and a packet approved wholesale would turn a
synthesis into ground truth without anybody having checked.

The two gold answers are in `packet_evidence.json`, keyed by `candidate_id`.
They are long, which is why they are not in the spreadsheet.
"""


def stable_fraction(value: str) -> float:
    return int(hashlib.sha256(value.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF


def build(sample: int) -> dict[str, Any]:
    payload = json.loads(CANDIDATES.read_text())
    candidates = payload["candidates"]

    # Spread the sample over category pairs rather than taking the top scores,
    # which would concentrate on whichever pairing the axis regex favours.
    by_pair: dict[tuple[str, ...], list[dict]] = defaultdict(list)
    for row in candidates:
        by_pair[tuple(sorted(row["required_categories"]))].append(row)
    chosen: list[dict] = []
    index = 0
    while len(chosen) < sample:
        added = False
        for pair in sorted(by_pair):
            rows = sorted(by_pair[pair],
                          key=lambda r: stable_fraction(r["candidate_id"]))
            if index < len(rows) and len(chosen) < sample:
                chosen.append(rows[index])
                added = True
        if not added:
            break
        index += 1

    PACKET_DIR.mkdir(exist_ok=True)
    with PACKET.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS)
        writer.writeheader()
        for row in chosen:
            writer.writerow({
                "candidate_id": row["candidate_id"],
                "split": row["split"],
                "issuer": row["issuer"],
                "categories": " + ".join(row["required_categories"]),
                "question_1": row["component_questions"][0],
                "question_2": row["component_questions"][1],
                "issuer_correct": "", "is_composite": "",
                "joint_answer_exists": "", "composite_question": "",
                "composite_answer": "", "notes": "",
            })
    (PACKET_DIR / "packet_evidence.json").write_text(json.dumps(
        {row["candidate_id"]: {
            "issuer": row["issuer"],
            "categories": row["required_categories"],
            "component_case_ids": row["component_case_ids"],
            "questions": row["component_questions"],
            "gold_answers": row["required_gold_slots"],
            "shared_decision_axes": row["shared_decision_axes"],
        } for row in chosen}, indent=2, ensure_ascii=False) + "\n")
    (PACKET_DIR / "README.md").write_text(GUIDE)

    pairs = Counter(" + ".join(r["required_categories"]) for r in chosen)
    return {"sampled": len(chosen), "available": len(candidates),
            "category_pairs": dict(pairs),
            "splits": dict(Counter(r["split"] for r in chosen))}


def read() -> dict[str, Any]:
    if not PACKET.is_file():
        raise SystemExit(f"no packet at {PACKET}; run --build first")
    rows = list(csv.DictReader(PACKET.open(encoding="utf-8")))

    def yes(value: str) -> bool | None:
        text = (value or "").strip().lower()
        if text in ("y", "yes", "true", "1"):
            return True
        if text in ("n", "no", "false", "0"):
            return False
        return None

    labelled, unlabelled, malformed = [], [], []
    for row in rows:
        verdicts = {k: yes(row.get(k, "")) for k in
                    ("issuer_correct", "is_composite", "joint_answer_exists")}
        if all(v is None for v in verdicts.values()):
            unlabelled.append(row["candidate_id"])
            continue
        if any(v is None for v in verdicts.values()):
            malformed.append({"candidate_id": row["candidate_id"],
                              "missing": [k for k, v in verdicts.items()
                                          if v is None]})
            continue
        usable = all(verdicts.values())
        if usable and not (row.get("composite_answer") or "").strip():
            malformed.append({"candidate_id": row["candidate_id"],
                              "missing": ["composite_answer"]})
            continue
        labelled.append({"candidate_id": row["candidate_id"],
                         "split": row["split"], "issuer": row["issuer"],
                         "categories": row["categories"], **verdicts,
                         "usable": usable,
                         "composite_question": row.get("composite_question", ""),
                         "composite_answer": row.get("composite_answer", ""),
                         "notes": row.get("notes", "")})

    usable = [r for r in labelled if r["usable"]]
    rejected = [r for r in labelled if not r["usable"]]
    reasons = Counter()
    for row in rejected:
        for key in ("issuer_correct", "is_composite", "joint_answer_exists"):
            if not row[key]:
                reasons[f"failed_{key}"] += 1

    return {"rows": len(rows), "labelled": len(labelled),
            "unlabelled": len(unlabelled), "malformed": malformed,
            "usable": len(usable), "rejected": len(rejected),
            "rejection_reasons": dict(reasons),
            "approval_rate": (round(len(usable) / len(labelled), 4)
                              if labelled else 0.0),
            "cases": labelled}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--build", action="store_true")
    ap.add_argument("--read", action="store_true")
    ap.add_argument("--sample", type=int, default=40)
    args = ap.parse_args()

    if args.build:
        summary = build(args.sample)
        print(f"{summary['sampled']} of {summary['available']} candidates "
              f"written to {PACKET.relative_to(ROOT)}")
        print(f"splits: {summary['splits']}")
        print("category pairs:")
        for pair, count in sorted(summary["category_pairs"].items()):
            print(f"  {pair:44s} {count}")
        print(f"\nguide: {(PACKET_DIR / 'README.md').relative_to(ROOT)}")
        print(f"gold answers: {(PACKET_DIR / 'packet_evidence.json').relative_to(ROOT)}")
        return 0

    if args.read:
        import sys
        sys.path.insert(0, str(ROOT / "experiments/minimal"))
        import observe

        run = observe.Run(OUT_ROOT, "adjudication", {"decisive": {
            "packet": str(PACKET.relative_to(ROOT)), "seed": 42}})
        with run.stage("read") as out:
            summary = read()
            out.update({k: v for k, v in summary.items()
                        if k not in ("cases", "malformed")})
            out["malformed"] = len(summary["malformed"])

        payload = {
            "contract": "log2026.cross_view_adjudication_human.v1",
            "question": ("Which synthesized cross-category candidates are real "
                         "questions with a joint answer?"),
            "method": ("a person judged each candidate on three counts: whether "
                       "the regex-inferred issuer is right, whether answering "
                       "needs both components, and whether the two gold answers "
                       "combine. All three must hold for a candidate to be "
                       "usable."),
            "claim_boundary": ("These questions are synthesized from pairs of "
                               "single-reference cases. Adjudication establishes "
                               "that a pairing is coherent, not that anyone ever "
                               "asked it. FinDER contains no natively "
                               "multi-source question, and no labelling changes "
                               "that."),
            **{k: v for k, v in summary.items() if k != "cases"},
            "cases": summary["cases"],
        }
        (run.dir / "adjudication.json").write_text(
            json.dumps(payload, indent=2, ensure_ascii=False) + "\n")

        print(f"{summary['rows']} rows: {summary['labelled']} labelled, "
              f"{summary['unlabelled']} unlabelled, "
              f"{len(summary['malformed'])} malformed")
        print(f"{summary['usable']} usable, {summary['rejected']} rejected "
              f"({summary['approval_rate']:.0%} approved)")
        for reason, count in sorted(summary["rejection_reasons"].items()):
            print(f"  {reason}: {count}")
        for entry in summary["malformed"][:8]:
            print(f"  incomplete {entry['candidate_id']}: "
                  f"{', '.join(entry['missing'])}")
        run.finish({"usable": summary["usable"],
                    "approval_rate": summary["approval_rate"],
                    "artifact": str((run.dir / "adjudication.json").relative_to(ROOT))})
        return 0

    ap.print_help()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
